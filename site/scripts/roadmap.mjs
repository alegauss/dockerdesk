// S2 — the build reads roadkeep. This runs `roadkeep export --json` against the governed
// files and writes src/lib/roadmap.generated.ts, so a shipped task moves the row it is on
// and nothing about this project's own progress is a number retyped by hand. If roadkeep
// cannot be reached or its output is malformed, this throws — a red build, never a page
// left confidently stale.
import { execFileSync } from "node:child_process";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { homedir } from "node:os";

const here = dirname(fileURLToPath(import.meta.url));
const siteDir = join(here, "..");
const repoRoot = join(siteDir, "..");
const outFile = join(siteDir, "src", "lib", "roadmap.generated.ts");

// Resolve a way to run roadkeep, mirroring .claude/hooks/roadkeep-launch.py: an explicit
// command, then roadkeep on PATH (what a CI job installs), then a checkout under a known
// root. The first candidate that returns valid JSON wins.
function candidates() {
  const list = [];
  if (process.env.ROADKEEP_CMD) {
    const parts = process.env.ROADKEEP_CMD.split(" ").filter(Boolean);
    list.push({ cmd: parts[0], pre: parts.slice(1) });
  }
  list.push({ cmd: "roadkeep", pre: [] });
  const cacheHome = process.env.XDG_CACHE_HOME || join(homedir(), ".cache");
  const roots = [
    process.env.ROADKEEP_HOME,
    join(repoRoot, "..", "roadkeep"),
    join(cacheHome, "roadkeep-src", "roadkeep"),
  ].filter(Boolean);
  for (const root of roots) {
    const engine = join(root, "scripts", "roadkeep.py");
    if (existsSync(engine)) list.push({ cmd: "python", pre: [engine] });
  }
  return list;
}

function runExport() {
  // -C is a global flag and must precede the subcommand.
  const args = ["-C", repoRoot, "export", "--json"];
  const errors = [];
  for (const { cmd, pre } of candidates()) {
    try {
      const out = execFileSync(cmd, [...pre, ...args], {
        encoding: "utf8",
        stdio: ["ignore", "pipe", "pipe"],
      });
      return JSON.parse(out);
    } catch (err) {
      errors.push(`${cmd} ${pre.join(" ")}: ${err.message.split("\n")[0]}`);
    }
  }
  throw new Error(
    "roadmap: could not run `roadkeep export --json`. Tried:\n  " + errors.join("\n  "),
  );
}

function slimTask(t) {
  return {
    id: t.id,
    status: t.status,
    block: t.block,
    symptom: t.symptom,
    why: t.why,
    deps: Array.isArray(t.deps) ? t.deps : [],
  };
}

const raw = runExport();

// Validate the shape before it becomes a page, so malformed roadkeep output is a red build.
for (const key of ["prefix", "blocks", "totals", "open", "ledger"]) {
  if (raw[key] === undefined) throw new Error(`roadmap: export is missing "${key}"`);
}
const open = raw.open.map(slimTask);
const ledger = raw.ledger.map(slimTask);
for (const t of [...open, ...ledger]) {
  if (!t.id || !t.status || !t.block) {
    throw new Error(`roadmap: a task is missing id/status/block: ${JSON.stringify(t)}`);
  }
}
const openIds = new Set(open.map((t) => t.id));
if (raw.next != null && !openIds.has(raw.next)) {
  throw new Error(`roadmap: next "${raw.next}" is not an open task`);
}

const data = {
  prefix: raw.prefix,
  blocks: raw.blocks,
  totals: raw.totals,
  open,
  ledger,
  next: raw.next ?? null,
};

const banner =
  "// GENERATED by scripts/roadmap.mjs from `roadkeep export --json` — do not edit by hand.\n" +
  "// Regenerated on every build (S2). Edit the roadmap through roadkeep, not this file.\n";

writeFileSync(
  outFile,
  banner +
    'import type { RoadmapData } from "./roadmap-types";\n\n' +
    "export const roadmap: RoadmapData = " +
    JSON.stringify(data, null, 2) +
    ";\n",
);

console.log(
  `roadmap: ${data.totals.shipped} shipped, ${data.totals.open} open across ${data.blocks.length} blocks -> src/lib/roadmap.generated.ts`,
);
