// S1 + S2 — the friction section on /claude-code argues with numbers, so none of them is
// typed. This reads the two files that own them and writes src/lib/surface.generated.ts:
//
//   agent-budget.json                        what the canonical task measured, and every
//                                            per-shape ceiling a test asserts (DD23)
//   src/DockerDesk.Tray/Cli/AgentSurface.cs  the verb registry — the table the router
//                                            dispatches on, so it is what actually exists
//
// The second one is the reason this script exists rather than a hand-kept list. The page
// says which verbs are shipped and which are still designed, and that claim goes false the
// day a verb lands — the one class of defect a site cannot notice about itself (S1). Read
// off the registry, it cannot: a verb that ships moves its own badge, and a verb renamed
// out from under the page fails the build in surface.test.mjs.
//
// A malformed or missing source throws. A red build, never a page left confidently stale.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const siteDir = join(here, "..");
const repoRoot = join(siteDir, "..");
const budgetFile = join(repoRoot, "agent-budget.json");
const registryFile = join(repoRoot, "src", "DockerDesk.Tray", "Cli", "AgentSurface.cs");
const outFile = join(siteDir, "src", "lib", "surface.generated.ts");

function read(path, what) {
  try {
    return readFileSync(path, "utf8");
  } catch (err) {
    throw new Error(`surface: cannot read ${what} at ${path}: ${err.message}`);
  }
}

// --- the budget file (DD23) ---

const budget = JSON.parse(read(budgetFile, "the budget file"));

function at(path) {
  let node = budget;
  for (const key of path.split(".")) {
    if (node == null || typeof node !== "object" || !(key in node)) {
      throw new Error(`surface: agent-budget.json is missing "${path}"`);
    }
    node = node[key];
  }
  return node;
}

function positive(path) {
  const value = at(path);
  if (typeof value !== "number" || !Number.isFinite(value) || value <= 0) {
    throw new Error(`surface: agent-budget.json "${path}" is not a positive number: ${value}`);
  }
  return value;
}

// Both `shapes` objects carry an `about` prose array beside the figures, and the surface
// half also carries `$<key>` entries recording what a raised ceiling bought. Numbers only.
function numbersIn(path) {
  const out = {};
  for (const [key, value] of Object.entries(at(path))) {
    if (typeof value === "number") out[key] = value;
  }
  if (Object.keys(out).length === 0) {
    throw new Error(`surface: agent-budget.json "${path}" carries no figures`);
  }
  return out;
}

const baseline = {
  task: at("baseline.task"),
  calls: positive("baseline.measured.calls"),
  tokens: positive("baseline.measured.tokens"),
  shapes: numbersIn("baseline.shapes"),
};

if (typeof baseline.task !== "string" || baseline.task.length === 0) {
  throw new Error("surface: agent-budget.json baseline.task is not a sentence");
}

const target = {
  calls: positive("surface.target.calls"),
  tokens: positive("surface.target.tokens"),
};

const ceilings = numbersIn("surface.shapes");

// --- the verb registry (DD24) ---
// The third constructor argument is AgentVerb.Shape, which is both how the verb is typed
// and the key its ceiling lives under in agent-budget.json — so one string joins the two
// sources and nothing here has to reconstruct a name.
const registry = read(registryFile, "the verb registry");
const shipped = [
  ...registry.matchAll(/new\(AgentNamespace\.(Read|Do),\s*"[a-z]+",\s*"([a-z ]+)"/g),
].map((m) => m[2]);

if (shipped.length === 0) {
  throw new Error(
    `surface: found no verbs in ${registryFile} — AgentSurface.All no longer matches the ` +
      "shape this script reads (new(AgentNamespace.X, \"name\", \"read name\", ...))",
  );
}

// The budget test in the solution demands a ceiling for every verb in the registry, so a
// verb here with none means the two files have drifted and one of them is wrong.
for (const verb of shipped) {
  if (ceilings[verb] === undefined) {
    throw new Error(`surface: verb "${verb}" exists but agent-budget.json gives it no ceiling`);
  }
}

const data = { baseline, target, ceilings, shipped };

const banner =
  "// GENERATED by scripts/surface.mjs from agent-budget.json and the AgentSurface verb\n" +
  "// registry — do not edit by hand. Regenerated on every build (S1, S2): the measured cost\n" +
  "// of the canonical task, the per-shape ceilings a test asserts, and which verbs exist today.\n";

writeFileSync(
  outFile,
  banner +
    'import type { SurfaceData } from "./surface-types";\n\n' +
    "export const surface: SurfaceData = " +
    JSON.stringify(data, null, 2) +
    ";\n",
);

console.log(
  `surface: baseline ${baseline.tokens} tok over ${baseline.calls} calls, ` +
    `${shipped.length} verb(s) shipped, ${Object.keys(ceilings).length} ceiling(s) ` +
    "-> src/lib/surface.generated.ts",
);
